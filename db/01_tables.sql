--------------------------------------------------------------------------------
-- Report Studio for Oracle APEX - tables
-- Run in the APEX workspace parsing schema. Requires Oracle 19c+ and APEX 22.1+.
--------------------------------------------------------------------------------

create table rpt_reports (
  report_id     number generated by default on null as identity primary key,
  code          varchar2(100 char) not null,
  name          varchar2(255 char) not null,
  description   varchar2(4000 char),
  layout        clob,
  status        varchar2(20 char) default 'DRAFT' not null,
  version_no    number default 0 not null,
  created_by    varchar2(255 char) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    date default sysdate not null,
  updated_by    varchar2(255 char),
  updated_on    date,
  constraint rpt_reports_code_uk unique (code),
  constraint rpt_reports_code_ck check (code = upper(code)),
  constraint rpt_reports_layout_ck check (layout is json),
  constraint rpt_reports_status_ck check (status in ('DRAFT','PUBLISHED','ARCHIVED'))
);

-- Named SQL queries (data sources) used by a report
create table rpt_sources (
  source_id     number generated by default on null as identity primary key,
  report_id     number not null references rpt_reports on delete cascade,
  name          varchar2(30 char) not null,
  sql_text      clob not null,
  test_params   clob,
  seq           number default 10 not null,
  constraint rpt_sources_uk unique (report_id, name),
  constraint rpt_sources_name_ck check (regexp_like(name, '^[A-Za-z][A-Za-z0-9_]*$')),
  constraint rpt_sources_tp_ck check (test_params is json)
);

-- Images (logos, signatures, stamps); shared across reports, referenced by CODE
create table rpt_assets (
  asset_id      number generated by default on null as identity primary key,
  code          varchar2(100 char) not null,
  file_name     varchar2(400 char),
  mime_type     varchar2(255 char) not null,
  content       blob not null,
  created_by    varchar2(255 char) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    date default sysdate not null,
  constraint rpt_assets_code_uk unique (code),
  constraint rpt_assets_code_ck check (code = upper(code))
);

-- Saved history of every layout save (rollback / audit)
create table rpt_versions (
  version_id    number generated by default on null as identity primary key,
  report_id     number not null references rpt_reports on delete cascade,
  version_no    number not null,
  layout        clob,
  sources       clob,
  saved_by      varchar2(255 char) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  saved_on      date default sysdate not null,
  constraint rpt_versions_layout_ck check (layout is json),
  constraint rpt_versions_sources_ck check (sources is json)
);
create index rpt_versions_rep_ix on rpt_versions (report_id, version_no);

-- Generation log
create table rpt_log (
  log_id        number generated by default on null as identity primary key,
  report_code   varchar2(100 char),
  output_type   varchar2(20 char),
  params        clob,
  bytes         number,
  duration_ms   number,
  status        varchar2(20 char),
  error_message varchar2(4000 char),
  created_by    varchar2(255 char) default coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  created_on    timestamp default systimestamp not null
);
create index rpt_log_code_ix on rpt_log (report_code, created_on);

